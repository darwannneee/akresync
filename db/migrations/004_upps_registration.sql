-- Registrasi mandiri UPPS (mengikuti alur SAKTI LAM Teknik) + data master institusi/jenjang/prodi.
-- Sumber master: db/seed/sakti-master.json (data referensi publik). Idempoten: aman dijalankan ulang.

-- ===== Master: institusi dengan id SAKTI =====
ALTER TABLE institutions ADD COLUMN IF NOT EXISTS sakti_id integer;
CREATE UNIQUE INDEX IF NOT EXISTS institutions_sakti_id_uq ON institutions(sakti_id);

-- ===== Master: jenjang dan nama program studi =====
CREATE TABLE IF NOT EXISTS levels (
  id     smallint PRIMARY KEY,
  code   text NOT NULL UNIQUE,
  label  text NOT NULL
);
CREATE TABLE IF NOT EXISTS program_names (
  id        integer PRIMARY KEY,
  sakti_id  integer NOT NULL UNIQUE,
  name      text NOT NULL
);

-- ===== study_programs: perluas jenjang + data tambahan prodi =====
ALTER TABLE study_programs DROP CONSTRAINT IF EXISTS study_programs_level_check;
ALTER TABLE study_programs ADD CONSTRAINT study_programs_level_check
  CHECK (level IN ('D3','D4','S1','S2','S3','PROFESI','D1','D2','PSPPI','STR','MTR','DTR'));
ALTER TABLE study_programs ADD COLUMN IF NOT EXISTS head_name text;
ALTER TABLE study_programs ADD COLUMN IF NOT EXISTS location  text;
ALTER TABLE study_programs ADD COLUMN IF NOT EXISTS lat       double precision;
ALTER TABLE study_programs ADD COLUMN IF NOT EXISTS lng       double precision;

-- ===== users: status akun (verifikasi Sekretariat Administrasi) =====
ALTER TABLE users ADD COLUMN IF NOT EXISTS status text NOT NULL DEFAULT 'active';
ALTER TABLE users DROP CONSTRAINT IF EXISTS users_status_check;
ALTER TABLE users ADD CONSTRAINT users_status_check CHECK (status IN ('active','pending_verification','rejected'));
-- Konsistensi: hanya status 'active' yang boleh is_active = true.
ALTER TABLE users DROP CONSTRAINT IF EXISTS users_status_active_check;
ALTER TABLE users ADD CONSTRAINT users_status_active_check CHECK (status = 'active' OR NOT is_active);

-- ===== Berkas tersimpan generik (terenkripsi AES-256-GCM, ciphertext di IPFS) =====
CREATE TABLE IF NOT EXISTS stored_files (
  id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  file_name    text NOT NULL,
  mime_type    text NOT NULL,
  size_bytes   bigint NOT NULL,
  sha256_plain char(64) NOT NULL,
  cid          text NOT NULL,
  wrapped_dek  bytea NOT NULL,
  dek_iv       bytea NOT NULL,
  dek_tag      bytea NOT NULL,
  file_iv      bytea NOT NULL,
  file_tag     bytea NOT NULL,
  created_at   timestamptz NOT NULL DEFAULT now()
);

-- ===== Registrasi UPPS =====
CREATE TABLE IF NOT EXISTS upps_registrations (
  id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id        uuid NOT NULL UNIQUE REFERENCES users(id),
  upps_name      text NOT NULL,
  leader_name    text NOT NULL,
  pic_name       text NOT NULL,
  phone          text,
  photo_file_id  uuid REFERENCES stored_files(id),
  sppa_file_id   uuid NOT NULL REFERENCES stored_files(id),
  spsu_file_id   uuid NOT NULL REFERENCES stored_files(id),
  status         text NOT NULL DEFAULT 'pending_verification' CHECK (status IN ('pending_verification','approved','rejected')),
  review_note    text,
  reviewed_by    uuid REFERENCES users(id),
  reviewed_at    timestamptz,
  created_at     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS upps_registrations_status_idx ON upps_registrations(status, created_at);

CREATE TABLE IF NOT EXISTS upps_registration_programs (
  id               uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  registration_id  uuid NOT NULL REFERENCES upps_registrations(id) ON DELETE CASCADE,
  level_id         smallint NOT NULL REFERENCES levels(id),
  program_name_id  integer NOT NULL REFERENCES program_names(id),
  head_name        text,
  location         text,
  lat              double precision,
  lng              double precision,
  position         smallint NOT NULL DEFAULT 0,
  UNIQUE (registration_id, level_id, program_name_id)
);

